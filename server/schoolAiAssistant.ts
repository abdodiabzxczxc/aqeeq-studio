function generateFollowUpQuestions(prompt: string): string[] {
  const p = prompt.toLowerCase();
  if (p.includes("تسجيل") || p.includes("قبول")) {
    return ["ما هي الأوراق والوثائق المطلوبة للتسجيل؟", "ما هي مواعيد الدوام المدرسي؟", "كيف أتواصل مع قسم القبول والتسجيل؟"];
  }
  if (p.includes("منهج") || p.includes("دولي") || p.includes("أمريكي")) {
    return ["ما هي مميزات الدبلومة الأمريكية بمدارس العقيق؟", "ما هي الأنشطة الإثرائية المعتمدة؟", "كيف يتم تأهيل الطلاب لاختبارات القدرات والتحصيلي؟"];
  }
  return ["كيف أبحث عن صوري في ألبومات التخرج؟", "ما هي أحدث فعاليات مدارس العقيق؟", "كيف أشارك بمقال في منصة العقيق؟"];
}
