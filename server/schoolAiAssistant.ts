function normalizeArabicText(text: string): string {
  return (text || "")
    .toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .trim();
}

function isGreeting(text: string): boolean {
  const greetings = [
    "مرحبا",
    "اهلين",
    "السلام عليكم",
    "صباح الخير",
    "مساء الخير",
    "هلا",
    "هاي",
    "hello",
    "hi",
    "من انت",
    "مين انت",
    "عرفني بنفسك",
    "ازيك",
    "شخبارك",
  ];
  return greetings.some((g) => text.includes(g)) && text.length < 40;
}

