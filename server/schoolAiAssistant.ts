export type ChatMessage = {
  role: "user" | "assistant";
  content: string;
};

export type ActionShortcut = {
  label: string;
  url: string;
  icon: string;
};

export async function askSchoolAiAssistant(
  messages: ChatMessage[],
  userPrompt: string
): Promise<{ reply: string; suggestedQuestions: string[]; actionShortcuts?: ActionShortcut[] }> {
  // 1. Fetch real-time live content summary to enrich the prompt context
  let livePlatformData = "";
  try {
    const [recentArticles, recentPodcasts, recentIssues, recentAlbums, broadcast] = await Promise.all([
      getPublishedArticles().catch(() => []),
      getPodcasts().catch(() => []),
      listSchoolNewsIssues("published").catch(() => []),
      listAqeeqAlbums("published").catch(() => []),
      getSiteBroadcast().catch(() => null),
    ]);

    const articlesSummary = (recentArticles as any[])
      .slice(0, 3)
      .map((a: any) => `• مقال: «${a.title}» للكاتب ${a.authorName} (${a.category})`)
      .join("\n");

    const podcastsSummary = (recentPodcasts as any[])
      .slice(0, 3)
      .map((p: any) => `• حلقة: «${p.title}» - ${p.category} (${p.mediaType === "video" ? "فيديو" : "صوت"})`)
      .join("\n");

    const issuesSummary = (recentIssues as any[])
      .slice(0, 2)
      .map((i: any) => `• عدد المجلة: «${i.title}»`)
      .join("\n");

    const albumsSummary = (recentAlbums as any[])
      .slice(0, 2)
      .map((alb: any) => `• ألبوم: «${alb.title}»`)
      .join("\n");

    livePlatformData = `
--- بيانات حية وفورية من المنصة حالياً ---
${broadcast?.enabled && broadcast.message ? `📢 تنبيه عاجل معلن في المنصة: "${broadcast.message}"` : ""}
${issuesSummary ? `أحدث أعداد مجلة العقيق المتاحة الآن:\n${issuesSummary}` : ""}
${albumsSummary ? `أحدث ألبومات الفعاليات المصورة:\n${albumsSummary}` : ""}
${articlesSummary ? `أحدث المقالات المنشورة في الاستوديو:\n${articlesSummary}` : ""}
${podcastsSummary ? `أحدث حلقات الإذاعة والبودكاست:\n${podcastsSummary}` : ""}
-----------------------------------------
`;
  } catch (e) {
    console.warn("Could not fetch live platform context for AI Assistant:", e);
  }

  // 2. Try Gemini API if key is provided
  const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;
  if (apiKey) {
    try {
      const ai = new GoogleGenAI({ apiKey });

      // Format multi-turn conversation history
      const formattedContents: any[] = [];

      // System instruction as first user message or system instruction
      const fullSystemContext = `${BASE_SCHOOL_KNOWLEDGE}\n\n${livePlatformData}`;

      formattedContents.push({
        role: "user",
        parts: [{ text: `[تعليمات النظام والمساعد الذكي لمدارس العقيق]:\n${fullSystemContext}\n\nيرجى الالتزام التام بالهوية والشخصية والمعلومات السابقة في كافة الردود.` }],
      });

      formattedContents.push({
        role: "model",
        parts: [{ text: "أهلاً بك! أنا المساعد الذكي لمدارس العقيق الأهلية والدولية بالمدينة المنورة. أنا جاهز للإجابة على جميع استفساراتك بأعلى درجات الدقة واللباقة." }],
      });

      // Add recent chat history turns (up to last 10 messages)
      const recentHistory = messages.slice(-10);
      for (const msg of recentHistory) {
        if (msg.role === "user") {
          formattedContents.push({
            role: "user",
            parts: [{ text: msg.content }],
          });
        } else if (msg.role === "assistant") {
          formattedContents.push({
            role: "model",
            parts: [{ text: msg.content }],
          });
        }
      }

      // Add the latest prompt
      formattedContents.push({
        role: "user",
        parts: [{ text: userPrompt }],
      });

      const res = await ai.models.generateContent({
        model: "gemini-2.5-flash",
        contents: formattedContents,
        config: {
          temperature: 0.65,
          maxOutputTokens: 1200,
        },
      });

      const rawReply = res.text?.trim();
      if (rawReply) {
        const suggestedQuestions = generateSmartFollowUpQuestions(userPrompt, rawReply);
        const actionShortcuts = generateActionShortcuts(userPrompt, rawReply);
        return {
          reply: rawReply,
          suggestedQuestions,
          actionShortcuts,
        };
      }
    } catch (err) {
      console.warn("Gemini AI Assistant generation failed, falling back to expert NLP knowledge base:", err);
    }
  }

  // 3. Fallback: Ultra-Rich Expert Knowledge Base
  return getExpertKnowledgeReply(userPrompt, messages);
}

