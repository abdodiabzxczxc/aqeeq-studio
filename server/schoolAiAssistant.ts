export type ChatMessage = {
  role: "user" | "assistant";
  content: string;
};

export async function askSchoolAiAssistant(
  messages: ChatMessage[],
  userPrompt: string
): Promise<{ reply: string; suggestedQuestions: string[] }> {
  try {
    const apiKey = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY;
    if (!apiKey) {
      return getFallbackReply(userPrompt);
    }

    const ai = new GoogleGenAI({ apiKey });

    const contents = [
      {
        role: "user",
        parts: [{ text: `${SCHOOL_KNOWLEDGE_CONTEXT}\n\nالسؤال الجديد من الزائر:\n${userPrompt}` }],
      },
    ];

    const res = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents,
      config: {
        temperature: 0.7,
        maxOutputTokens: 800,
      },
    });

    const reply = res.text?.trim() || getFallbackReply(userPrompt).reply;
    const suggestedQuestions = generateFollowUpQuestions(userPrompt);

    return {
      reply,
      suggestedQuestions,
    };
  } catch (err) {
    console.warn("AI Assistant error, using smart fallback:", err);
    return getFallbackReply(userPrompt);
  }
}

